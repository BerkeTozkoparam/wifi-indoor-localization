"""## 6. FCN + YOLO Ensemble Pipeline

**Ensemble mantığı:**
- YOLO her bbox için conf ve sınıf üretir
- FCN, bbox bölgesinin ortalama anomaly skorunu üretir
- `ensemble_score = yolo_conf × (1 + α × fcn_score)`
- Good Weld detection'larında FCN skoru düşükse ceza uygulanır
- Bu sayede FCN, YOLO'nun false positive'lerini filtreler
"""

# ── Pipeline sabitleri ────────────────────────────────────────────────────
FCN_THRESHOLD  = 0.4   # Anomaly mask eşiği
YOLO_CONF      = 0.20  # YOLO minimum confidence
YOLO_IOU       = 0.45
ALPHA          = 0.4   # FCN boost katsayısı
FINAL_CONF_THR = 0.18  # Ensemble sonrası minimum skor
ANOMALY_CLS    = {0, 2}  # Bad Weld, Defect
# ─────────────────────────────────────────────────────────────────────────

fcn_model.load_state_dict(torch.load(FCN_SAVE_PATH, map_location=device))
fcn_model.eval()
print('FCN yüklendi.')

yolo_det    = YOLO(YOLO_BEST)
class_names = list(yolo_det.names.values())
print(f'YOLO yüklendi. Sınıflar: {class_names}')


@torch.no_grad()
def fcn_predict(img_bgr):
    """FCN anomaly probability map üret (orijinal boyutta)"""
    H, W = img_bgr.shape[:2]
    rgb  = cv2.cvtColor(img_bgr, cv2.COLOR_BGR2RGB)
    inp  = cv2.resize(rgb, (FCN_IMG_SIZE, FCN_IMG_SIZE))
    t    = torch.from_numpy(inp.astype(np.float32)/255.).permute(2,0,1).unsqueeze(0).to(device)
    prob = fcn_model(t).squeeze().cpu().numpy()
    prob_full   = cv2.resize(prob, (W, H))
    binary_mask = (prob_full > FCN_THRESHOLD).astype(np.uint8) * 255
    return binary_mask, prob_full


def ensemble_pipeline(img_bgr):
    """
    FCN + YOLO Ensemble:
    1. YOLO tüm görüntüde detection yapar
    2. FCN anomaly map üretir
    3. Her detection için bbox bölgesindeki FCN skoru hesaplanır
    4. Anomaly sınıflarında FCN boost, Good Weld'de FCN cezası uygulanır
    5. ensemble_score = yolo_conf × (1 + α × fcn_mean)
    """
    H, W = img_bgr.shape[:2]

    # YOLO
    raw_dets = []
    for r in yolo_det(img_bgr, conf=YOLO_CONF, iou=YOLO_IOU, verbose=False):
        for box in r.boxes:
            bx1,by1,bx2,by2 = map(int, box.xyxy[0].tolist())
            raw_dets.append([bx1,by1,bx2,by2, float(box.conf[0]), int(box.cls[0])])

    # FCN anomaly map
    binary_mask, prob_map = fcn_predict(img_bgr)

    # Ensemble skoru
    final_dets = []
    for bx1,by1,bx2,by2,yolo_conf,cls in raw_dets:
        # Bbox bölgesindeki FCN ortalama anomaly skoru
        bx1c = max(0, bx1); by1c = max(0, by1)
        bx2c = min(W, bx2); by2c = min(H, by2)
        roi_prob = prob_map[by1c:by2c, bx1c:bx2c]
        fcn_mean = float(roi_prob.mean()) if roi_prob.size > 0 else 0.0

        if cls in ANOMALY_CLS:
            # Anomaly sınıfı: FCN yüksekse boost
            ensemble = yolo_conf * (1 + ALPHA * fcn_mean)
        else:
            # Good Weld: FCN yüksekse şüpheli → ceza
            ensemble = yolo_conf * (1 - ALPHA * fcn_mean)

        ensemble = float(np.clip(ensemble, 0, 1))
        if ensemble >= FINAL_CONF_THR:
            final_dets.append((bx1,by1,bx2,by2, yolo_conf, ensemble, cls, fcn_mean))

    return final_dets, binary_mask, prob_map


# Renk: Bad Weld=kırmızı, Good Weld=yeşil, Defect=turuncu
CLS_COLORS = {0: (60,60,255), 1: (60,200,60), 2: (60,165,255)}

def visualize(img_bgr, detections, prob_map):
    out  = img_bgr.copy()
    heat = cv2.applyColorMap((prob_map * 255).astype(np.uint8), cv2.COLORMAP_JET)
    out  = cv2.addWeighted(out, 0.72, heat, 0.28, 0)

    for (bx1,by1,bx2,by2,yolo_conf,ensemble,cls,fcn_mean) in detections:
        color = CLS_COLORS.get(cls, (200,200,200))
        cv2.rectangle(out, (bx1,by1), (bx2,by2), color, 2)
        name  = class_names[cls] if cls < len(class_names) else f'cls{cls}'
        label = f'{name} Y:{yolo_conf:.2f} E:{ensemble:.2f} F:{fcn_mean:.2f}'
        (tw,th),_ = cv2.getTextSize(label, cv2.FONT_HERSHEY_SIMPLEX, 0.5, 1)
        cv2.rectangle(out, (bx1, by1-th-6), (bx1+tw+4, by1), color, -1)
        cv2.putText(out, label, (bx1+2, by1-4),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.5, (255,255,255), 1)

    n_anomaly = sum(1 for d in detections if d[6] in ANOMALY_CLS)
    cv2.putText(out, f'Det:{len(detections)} Anomaly:{n_anomaly}',
                (10,32), cv2.FONT_HERSHEY_SIMPLEX, 0.8, (255,255,255), 2)
    return out


