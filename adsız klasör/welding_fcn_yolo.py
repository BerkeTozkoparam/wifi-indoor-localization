"""## 4. FCN Dataset & Eğitim

**Mask stratejisi:** YOLO bbox → binary mask
- `Bad Weld` (cls=0) → mask=1 (anomaly)
- `Defect`   (cls=2) → mask=1 (anomaly)  
- `Good Weld`(cls=1) → mask=0 (normal)

FCN gerçek bbox'larla eğitildiği için lokalize anomali haritası üretir.
"""

class WeldingDefectDataset(Dataset):
    """
    YOLO bbox → binary anomaly mask
    Bad Weld (0) + Defect (2) → mask=1
    Good Weld (1)             → mask=0
    """
    ANOMALY_CLASSES = {0, 2}  # Bad Weld, Defect

    def __init__(self, root, img_size=640, augment=False):
        self.img_size = img_size
        self.augment  = augment
        img_dir = Path(root) / 'images'
        lbl_dir = Path(root) / 'labels'
        self.samples = []
        for p in sorted(img_dir.iterdir()):
            if p.suffix.lower() in ('.jpg', '.jpeg', '.png'):
                lbl = lbl_dir / (p.stem + '.txt')
                if lbl.exists():
                    self.samples.append((str(p), str(lbl)))
        print(f'[Dataset] {len(self.samples)} örnek: {root}')

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, idx):
        img_path, lbl_path = self.samples[idx]
        img = cv2.cvtColor(cv2.imread(img_path), cv2.COLOR_BGR2RGB)
        H, W = img.shape[:2]

        mask = np.zeros((H, W), dtype=np.float32)
        with open(lbl_path) as f:
            for line in f:
                parts = line.strip().split()
                if len(parts) < 5: continue
                cls = int(parts[0])
                if cls not in self.ANOMALY_CLASSES: continue
                cx, cy, bw, bh = map(float, parts[1:5])
                x1 = max(0, int((cx - bw/2) * W))
                y1 = max(0, int((cy - bh/2) * H))
                x2 = min(W, int((cx + bw/2) * W))
                y2 = min(H, int((cy + bh/2) * H))
                mask[y1:y2, x1:x2] = 1.0

        img  = cv2.resize(img,  (self.img_size, self.img_size))
        mask = cv2.resize(mask, (self.img_size, self.img_size),
                          interpolation=cv2.INTER_NEAREST)

        if self.augment:
            if np.random.random() > 0.5:
                img  = cv2.flip(img,  1)
                mask = cv2.flip(mask, 1)
            if np.random.random() > 0.5:
                img  = cv2.flip(img,  0)
                mask = cv2.flip(mask, 0)

        img_t  = torch.from_numpy(img.astype(np.float32) / 255.0).permute(2,0,1)
        mask_t = torch.from_numpy(mask).unsqueeze(0)
        return img_t, mask_t


def collate_fn(batch):
    return torch.stack([b[0] for b in batch]), torch.stack([b[1] for b in batch])


def iou_score(pred, target, thr=0.5):
    p = (pred.squeeze() > thr).float()
    t = target.squeeze().float()
    inter = (p * t).sum().item()
    union = (p + t).clamp(0, 1).sum().item()
    return inter / union if union >= 1 else float('nan')


def mean_iou(preds, targets, thr=0.5):
    scores = [iou_score(preds[i], targets[i], thr) for i in range(preds.shape[0])]
    valid  = [s for s in scores if s == s]
    return float(np.mean(valid)) if valid else float('nan')


