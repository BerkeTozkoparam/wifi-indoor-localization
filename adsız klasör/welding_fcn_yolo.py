fcn_model = FCNAnomalyDetector().to(device)
criterion = DiceLoss()
optimizer = optim.AdamW(fcn_model.parameters(), lr=FCN_LR, weight_decay=1e-4)
scheduler = optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=FCN_EPOCHS)

best_val_loss = float('inf')
best_iou      = 0.0
no_improve    = 0
history       = {'tr_loss': [], 'vl_loss': [], 'tr_iou': [], 'vl_iou': []}

print(f"{'Epoch':>6} {'Tr Loss':>9} {'Tr IoU':>8} {'Vl Loss':>9} {'Vl IoU':>8} {'Süre':>7}")
print('-' * 55)

for epoch in range(1, FCN_EPOCHS + 1):
    t0 = time.time()

    # Train
    fcn_model.train()
    tr_loss, tr_iou_sum, tr_iou_n = 0.0, 0.0, 0
    for imgs, masks in tr_loader:
        imgs, masks = imgs.to(device), masks.to(device)
        optimizer.zero_grad()
        preds = fcn_model(imgs)
        loss  = criterion(preds, masks)
        loss.backward()
        optimizer.step()
        tr_loss += loss.item()
        bi = mean_iou(preds.detach().cpu(), masks.cpu())
        if bi == bi: tr_iou_sum += bi; tr_iou_n += 1

    # Validation
    fcn_model.eval()
    vl_loss, vl_iou_sum, vl_iou_n = 0.0, 0.0, 0
    with torch.no_grad():
        for imgs, masks in vl_loader:
            imgs, masks = imgs.to(device), masks.to(device)
            preds = fcn_model(imgs)
            vl_loss += criterion(preds, masks).item()
            bi = mean_iou(preds.cpu(), masks.cpu())
            if bi == bi: vl_iou_sum += bi; vl_iou_n += 1

    scheduler.step()

    tl = tr_loss    / len(tr_loader)
    ti = tr_iou_sum / max(tr_iou_n, 1)
    vl = vl_loss    / len(vl_loader)
    vi = vl_iou_sum / max(vl_iou_n, 1)
    history['tr_loss'].append(tl); history['tr_iou'].append(ti)
    history['vl_loss'].append(vl); history['vl_iou'].append(vi)

    flag = ''
    if vl < best_val_loss - MIN_DELTA:
        best_val_loss = vl
        best_iou      = vi
        no_improve    = 0
        torch.save(fcn_model.state_dict(), FCN_SAVE_PATH)
        flag = '  ✓ saved'
    else:
        no_improve += 1
        flag = f'  [{no_improve}/{PATIENCE}]'

    print(f"{epoch:>6} {tl:>9.4f} {ti:>8.4f} {vl:>9.4f} {vi:>8.4f} {time.time()-t0:>6.1f}s{flag}")

    if no_improve >= PATIENCE:
        print(f'\n⏹ Early stopping: {PATIENCE} epoch iyileşme yok.')
        break

print(f'\nFCN tamamlandı. Val Loss: {best_val_loss:.4f} | IoU: {best_iou:.4f}')

